"""reports/RESULTS.md + reports/summary.json from every results/*.json (no model calls)."""

from __future__ import annotations

import json
from pathlib import Path

from mcpagent.evaluation import load_results, load_tasks, summarize


def write_report(root: Path) -> tuple[Path, list[dict]]:
    tasks = load_tasks(root / "tasks.jsonl")
    rows, per_task = [], {}
    for f in sorted((root / "results").glob("*.json")):
        data = load_results(f)
        rows.append(summarize(f.stem, data, tasks))
        per_task[f.stem] = data
    lines = [
        "# Results",
        "",
        "Generated by `mcpagent report` from `results/*.json`. Do not edit by hand.",
        "",
        "| Run (provider__model__search) | Right tool (first call) | Right tool (any call) "
        "| Answer correct | Stopped at 5 steps | Avg steps | Avg time | Model time | Tool time |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['label']} | {r['right_tool_first']}/{r['n']} | {r['right_tool_any']}/{r['n']} "
            f"| {r['answer_correct']}/{r['n']} | {r['stopped']} | {r['avg_steps']} "
            f"| {r['avg_seconds']} s | {r['avg_llm_seconds']} s | {r['avg_tool_seconds']} s |"
        )
    lines += ["", "## Per task", ""]
    head = "| Task | Expected tool | " + " | ".join(r["label"] for r in rows) + " |"
    lines += [head, "|" + "---|" * (2 + len(rows))]
    for t in tasks:
        cells = []
        for r in rows:
            d = per_task[r["label"]].get(t["id"])
            if d is None:
                cells.append("-")
                continue
            tools = ",".join(d["tools_called"]) or "(none)"
            cells.append(f"{'✅' if d['answer_correct'] else '❌'} {tools}")
        lines.append(f"| {t['id']} | {t['tool']} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "Right tool (first call) = the first tool the model called is the expected one. "
        "Answer correct = automatic check (expected text in the answer, or the note file really "
        "written). Times are wall clock on the machine that ran the evaluation.",
        "",
    ]
    out = root / "reports" / "RESULTS.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes("\n".join(lines).encode("utf-8"))
    (root / "reports" / "summary.json").write_bytes((json.dumps(rows, indent=1) + "\n").encode("utf-8"))
    return out, rows
